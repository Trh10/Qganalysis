// Language switcher logic
(function() {
    let currentLang = localStorage.getItem('qg_lang') || 'fr';

    function applyTranslations(lang) {
        const t = translations[lang];
        if (!t) return;

        // Update all elements with data-i18n
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (t[key] !== undefined) {
                if (el instanceof SVGElement) {
                    el.textContent = t[key];
                } else if (/<[a-z][\s\S]*>/i.test(t[key])) {
                    el.innerHTML = t[key];
                } else {
                    el.textContent = t[key];
                }
            }
        });

        // Force update hero rotating words by restarting animation
        const rotateInner = document.querySelector('.hero-rotate-inner');
        if (rotateInner) {
            rotateInner.style.animation = 'none';
            rotateInner.offsetHeight; // force reflow
            rotateInner.style.animation = '';
        }

        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            if (t[key] !== undefined) {
                el.setAttribute('placeholder', t[key]);
            }
        });

        // Handle RTL for Arabic
        if (lang === 'ar') {
            document.documentElement.setAttribute('dir', 'rtl');
            document.documentElement.setAttribute('lang', 'ar');
        } else {
            document.documentElement.setAttribute('dir', 'ltr');
            document.documentElement.setAttribute('lang', lang);
        }

        // Update active lang button
        document.querySelectorAll('.lang-btn').forEach(btn => {
            btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
        });

        currentLang = lang;
        localStorage.setItem('qg_lang', lang);
    }

    // Init on DOM ready
    document.addEventListener('DOMContentLoaded', function() {
        // Set up lang buttons
        document.querySelectorAll('.lang-btn').forEach(btn => {
            btn.addEventListener('click', function(e) {
                e.preventDefault();
                const lang = this.getAttribute('data-lang');
                applyTranslations(lang);
            });
        });

        // Apply saved language
        if (currentLang !== 'fr') {
            applyTranslations(currentLang);
        } else {
            document.querySelectorAll('.lang-btn').forEach(btn => {
                btn.classList.toggle('active', btn.getAttribute('data-lang') === 'fr');
            });
        }
    });
})();
